from typing import Optional, List

from fastapi import APIRouter, Depends, HTTPException, Request
from pydantic import BaseModel, Field

from server.context import get_config_parser, get_db_session
from server.security.auth import verify_token
from configparser import ConfigParser
from sqlalchemy.orm import Session
from server.repository.character_repository import CharacterRepository, CharacterProfile as CharacterProfileData


router = APIRouter(prefix="/character", tags=["Character"])


class CreateCharacterRequest(BaseModel):
    gender: str = Field(..., description="Character gender")
    region: str = Field(..., description="Character region")
    job: str = Field(..., description="Character job")


class CharacterProfile(BaseModel):
    character_id: int
    user_id: str
    gender: str
    region: str
    job: str


class UpdateCharacterRequest(BaseModel):
    gender: Optional[str] = Field(None, description="Character gender")
    region: Optional[str] = Field(None, description="Character region")
    job: Optional[str] = Field(None, description="Character job")


def get_current_user_id(
    request: Request,
    parser: ConfigParser = Depends(get_config_parser),
) -> str:
    """Get current user_id from token (from cookie or query parameter)"""
    # Try to get token from cookie first, then query parameter
    token = request.cookies.get("token") or request.query_params.get("token")
    
    if not token:
        raise HTTPException(status_code=401, detail="Token required (provide via cookie or query parameter)")
    
    user_claims = verify_token(token, parser)
    user_id = user_claims.get("user_id")
    if not user_id:
        raise HTTPException(status_code=401, detail="Invalid token payload")
    
    return user_id


@router.post("", response_model=CharacterProfile, status_code=201)
async def create_character(
    req: CreateCharacterRequest,
    request: Request,
    db: Session = Depends(get_db_session),
    parser: ConfigParser = Depends(get_config_parser),
):
    """Create a new character for the current user"""
    user_id = get_current_user_id(request, parser)
    
    repo = CharacterRepository(db)
    
    # Create character (character_id will be generated by database)
    created = repo.create(
        user_id=user_id,
        gender=req.gender,
        region=req.region,
        job=req.job,
    )
    
    return CharacterProfile(
        character_id=created.character_id,
        user_id=created.user_id,
        gender=created.gender,
        region=created.region,
        job=created.job,
    )


@router.get("", response_model=List[CharacterProfile])
async def get_characters(
    request: Request,
    db: Session = Depends(get_db_session),
    parser: ConfigParser = Depends(get_config_parser),
):
    """Get all characters for the current user"""
    user_id = get_current_user_id(request, parser)
    
    repo = CharacterRepository(db)
    characters = repo.get_by_user_id(user_id)
    
    return [
        CharacterProfile(
            character_id=char.character_id,
            user_id=char.user_id,
            gender=char.gender,
            region=char.region,
            job=char.job,
        )
        for char in characters
    ]


@router.get("/{character_id}", response_model=CharacterProfile)
async def get_character(
    character_id: int,
    request: Request,
    db: Session = Depends(get_db_session),
    parser: ConfigParser = Depends(get_config_parser),
):
    """Get a specific character by ID (must belong to current user)"""
    user_id = get_current_user_id(request, parser)
    
    repo = CharacterRepository(db)
    character = repo.get(character_id)
    
    if not character:
        raise HTTPException(status_code=404, detail="Character not found")
    
    if character.user_id != user_id:
        raise HTTPException(status_code=403, detail="Access denied")
    
    return CharacterProfile(
        character_id=character.character_id,
        user_id=character.user_id,
        gender=character.gender,
        region=character.region,
        job=character.job,
    )


@router.put("/{character_id}", response_model=CharacterProfile)
async def update_character(
    character_id: int,
    req: UpdateCharacterRequest,
    request: Request,
    db: Session = Depends(get_db_session),
    parser: ConfigParser = Depends(get_config_parser),
):
    """Update a character (must belong to current user)"""
    user_id = get_current_user_id(request, parser)
    
    repo = CharacterRepository(db)
    character = repo.get(character_id)
    
    if not character:
        raise HTTPException(status_code=404, detail="Character not found")
    
    if character.user_id != user_id:
        raise HTTPException(status_code=403, detail="Access denied")
    
    updated = repo.update(
        character_id,
        gender=req.gender,
        region=req.region,
        job=req.job,
    )
    
    if not updated:
        raise HTTPException(status_code=404, detail="Character not found")
    
    return CharacterProfile(
        character_id=updated.character_id,
        user_id=updated.user_id,
        gender=updated.gender,
        region=updated.region,
        job=updated.job,
    )


@router.delete("/{character_id}", status_code=204)
async def delete_character(
    character_id: int,
    request: Request,
    db: Session = Depends(get_db_session),
    parser: ConfigParser = Depends(get_config_parser),
):
    """Delete a character (must belong to current user)"""
    user_id = get_current_user_id(request, parser)
    
    repo = CharacterRepository(db)
    character = repo.get(character_id)
    
    if not character:
        raise HTTPException(status_code=404, detail="Character not found")
    
    if character.user_id != user_id:
        raise HTTPException(status_code=403, detail="Access denied")
    
    success = repo.delete(character_id)
    if not success:
        raise HTTPException(status_code=404, detail="Character not found")
    
    return None

